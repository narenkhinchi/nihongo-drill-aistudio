    fun getAllLessons(): List<LessonInfo> = (1..25).map { number ->
        val count = getVocabForLesson(number).size
        LessonInfo(number, "Lesson $number", "", if (count == 0)
            "Awaiting book vocabulary" else "$count words from your book", count)
    }
    fun getLessonInfo(number: Int): LessonInfo? = getAllLessons().find { it.lessonNumber == number }
    fun getVocabForLesson(number: Int): List<VocabItem> = vocabList.filter { it.lessonNumber == number }
    fun getAllVocab(): List<VocabItem> = vocabList
    fun getDistractors(correct: VocabItem, count: Int, direction: DrillDirection): List<String> {
        fun answer(item: VocabItem) = if (direction == DrillDirection.ENGLISH_TO_HIRAGANA ||
            direction == DrillDirection.KANJI_TO_KANA) item.kana else item.english
        val target = answer(correct)
        return vocabList.filter { it.id != correct.id }
            .sortedBy { if (it.lessonNumber == correct.lessonNumber) 0 else 1 }
            .map(::answer).filter { it != target }.distinct().take(20).shuffled().take(count)
    }
